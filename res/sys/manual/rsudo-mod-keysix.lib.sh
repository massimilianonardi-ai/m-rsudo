NAME
    rsudo keysix — administration of linked APISIX and Keycloak instances

SYNOPSIS
    rsudo [rsudo-options...] keysix help

DESCRIPTION
    rsudo keysix amministra istanze collegate di APISIX e Keycloak
    per la gestione di servizi web protetti da autenticazione e
    autorizzazioni basate sui ruoli (RBAC).

CURRENT STATUS
    Il modulo iniziale contiene esclusivamente la funzione help.
    Non esegue ancora operazioni amministrative su APISIX o Keycloak.
