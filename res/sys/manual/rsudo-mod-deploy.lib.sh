NAME
    rsudo-mod-deploy.lib.sh — native rsudo deploy CLI module

SYNOPSIS
    rsudo [rsudo-options] deploy help

DESCRIPTION
    The rsudo dispatcher resolves the deploy module using its existing
    m-rsudo package lookup and credential handling. The first implementation
    exposes help only; resource administration comes in subsequent revisions.

    The interactive menu lives in rsudo-deploy.lib.sh and may be opened with
    rsudo-deploy or the Deploy entry in rsudo-admin.

